int	ft_strcmp(char *s1, char *s2)
{
	int sdiff;
	int i;

	sdiff =0;
	if ((!s2) && (!s1))
		return (0);
	//if (s1 == s2)
	//	return (0);
	while ( s1[i] == s2[i] && *s1)
	{
		i++;
	}
	sdiff = s1[i] - s2[i];
	return (sdiff);
}

